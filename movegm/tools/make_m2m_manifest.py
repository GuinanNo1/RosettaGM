"""Regenerate js/m2m-manifest.js (the slim manifest MIDI2Move needs) from data/movegm-manifest.json.

Run from movegm/:  python3 tools/make_m2m_manifest.py
After a MoveGM rebuild, copy the new movegm-manifest.json (written by build.py) to data/ first,
then bump MIDI2Move's version and the ?v= tags in midi2move/index.html.
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__)); base = os.path.dirname(here)
man = json.load(open(os.path.join(base, 'data', 'movegm-manifest.json')))
slim = {'programs': [{k: p[k] for k in ('program', 'name', 'preset', 'sample', 'render_key', 'volume_db', 'env')} for p in man['programs']],
        'kits': [{'name': k['name'], 'preset': k['preset'], 'pads': [{'pad': x['pad'], 'sample': x['sample']} for x in k['pads']]} for k in man['kits']],
        'drift': man['drift'], 'fold_to_core': {int(k): v for k, v in man['fold_to_core'].items()}}
with open(os.path.join(base, 'js', 'm2m-manifest.js'), 'w') as f:
    f.write('/* Generated by movegm/tools/make_m2m_manifest.py from data/movegm-manifest.json (MoveGM v0.2). */\n'
            'window.M2M_MANIFEST = ' + json.dumps(slim, separators=(',', ':')) + ';\n')
print('wrote js/m2m-manifest.js')
